"""
Unit tests for file filtering, binary detection, and classification (§8.2).
"""

import os
import tempfile

from app.services.ingestion.filter import (
    IngestionFilter,
    classify_file_kind,
    detect_language,
    is_binary_file,
    is_minified_or_generated,
)


def test_language_detection_and_kind_classification():
    assert detect_language("app/main.py") == "python"
    assert classify_file_kind("app/main.py", "python") == "code"

    assert detect_language("src/components/Button.tsx") == "typescript"
    assert classify_file_kind("src/components/Button.tsx", "typescript") == "code"

    assert detect_language("README.md") == "markdown"
    assert classify_file_kind("README.md", "markdown") == "doc"

    assert detect_language("docker-compose.yml") == "yaml"
    assert classify_file_kind("docker-compose.yml", "yaml") == "config"

    assert classify_file_kind("tests/test_auth.py", "python") == "test"
    assert classify_file_kind("src/api.test.ts", "typescript") == "test"


def test_binary_detection():
    with tempfile.TemporaryDirectory() as tmpdir:
        text_file = os.path.join(tmpdir, "normal.txt")
        with open(text_file, "w", encoding="utf-8") as f:
            f.write("This is a normal UTF-8 text file.\nSecond line.\n")
        assert is_binary_file(text_file) is False

        bin_file = os.path.join(tmpdir, "binary.dat")
        with open(bin_file, "wb") as f:
            f.write(b"PNG\x0d\x0a\x1a\x0a\x00\x00\x00\x0dIHDR")
        assert is_binary_file(bin_file) is True


def test_minified_and_generated_detection():
    # Long line (> 300 chars)
    long_line = ["const x = " + "a" * 400 + ";\n"]
    is_min, reason = is_minified_or_generated(long_line)
    assert is_min is True
    assert reason == "minified"

    # Generated file header
    gen_lines = [
        "// Code generated by protoc-gen-go. DO NOT EDIT.\n",
        "package pb\n",
        "type User struct {}\n",
    ]
    is_gen, gen_reason = is_minified_or_generated(gen_lines)
    assert is_gen is True
    assert gen_reason == "generated"

    # Normal code
    normal_lines = [
        "def add(a: int, b: int) -> int:\n",
        "    return a + b\n",
    ]
    is_normal, _ = is_minified_or_generated(normal_lines)
    assert is_normal is False


def test_ingestion_filter_scan():
    with tempfile.TemporaryDirectory() as tmpdir:
        # Create normal files
        os.makedirs(os.path.join(tmpdir, "src"), exist_ok=True)
        with open(os.path.join(tmpdir, "src", "index.ts"), "w", encoding="utf-8") as f:
            f.write("export const app = 'test';\n")

        with open(os.path.join(tmpdir, "README.md"), "w", encoding="utf-8") as f:
            f.write("# Project Title\nDocumentation.\n")

        # Create ignored items
        os.makedirs(os.path.join(tmpdir, "node_modules", "pkg"), exist_ok=True)
        with open(
            os.path.join(tmpdir, "node_modules", "pkg", "index.js"), "w", encoding="utf-8"
        ) as f:
            f.write("module.exports = {};\n")

        with open(os.path.join(tmpdir, "package-lock.json"), "w", encoding="utf-8") as f:
            f.write("{}\n")

        with open(os.path.join(tmpdir, "logo.png"), "wb") as f:
            f.write(b"\x89PNG\r\n\x1a\n\x00\x00")

        flt = IngestionFilter(root_dir=tmpdir)
        valid, skipped = flt.scan_and_filter()

        valid_paths = [v["path"] for v in valid]
        assert "src/index.ts" in valid_paths
        assert "README.md" in valid_paths
        assert not any("node_modules" in p for p in valid_paths)

        skipped_paths = [s["path"] for s in skipped]
        assert "package-lock.json" in skipped_paths
        assert "logo.png" in skipped_paths
